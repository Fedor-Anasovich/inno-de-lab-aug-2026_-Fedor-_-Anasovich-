# Исходный список строк, имитирующий сырые логи транзакций.
# Каждая запись содержит статус (SUCCESS, FAILED, ERROR) и сумму через двоеточие.
transaction = ["SUCCESS:100", "FAILED:50", "SUCCESS:-10", "SUCCESS:0", "SUCCESS:250", "ERROR:200"]

# Однострочное списковое включение (List Comprehension).
# Оно одновременно фильтрует элементы и преобразует их в числа. Разберем его справа налево:
# 1. for tx in transaction — циклически перебирает каждую строку (tx) из списка transaction.
# 2. if tx.startswith("SUCCESS:") — условие №1: оставляет только те строки, которые начинаются со слова "SUCCESS:".
# 3. and int(tx.split(":")[1]) > 0 — условие №2: разбивает строку по двоеточию, берет правую часть (сумму),
#    превращает её в целое число с помощью int() и проверяет, что сумма строго больше нуля.
# 4. int(tx.split(":")[1]) (в самом начале) — то, что пойдет в итоговый список, если оба условия (2 и 3) сошлись.
#    Здесь мы снова берем сумму и конвертируем её в integer.
valid_amounts = [int(tx.split(":")[1]) for tx in transaction if tx.startswith("SUCCESS:") and int(tx.split(":")[1]) > 0]

# Выводим полученный список очищенных числовых значений в консоль.
# Результат: [100, 250]
print(f"Очищенные транзакции: {valid_amounts}")
