# Исходный список кортежей (коллекция фиксированных структур данных).
# Каждый кортеж содержит 4 элемента: имя сервера, нагрузку CPU (%), использование RAM (%) и статус.
system_telemetry = [
    ("srv_01", 12.5, 64, "online"),
    ("srv_02", 85.0, 92, "online"),
    ("srv_03", 0.0, 0, "offline"),
    ("srv_04", 45.2, 78, "online"),
    ("srv_05", 95.1, 99, "online")
]

# Инициализируем пустые списки, в которые будем собирать отфильтрованные метрики.
active_nodes = []  # Для имен работающих серверов
cpu_loads = []  # Для показателей нагрузки процессора
ram_usages = []  # Для показателей заполненности оперативной памяти

# Запускаем цикл for. Мы применяем распаковку кортежа (Tuple Unpacking) прямо в заголовке цикла.
# На каждой итерации 4 элемента текущего кортежа автоматически раскладываются в 4 переменные.
for node_name, cpu_load, ram_usage, status in system_telemetry:
    # Проверяем условие фильтрации: если статус сервера равен "offline"
    if status == "offline":
        # Оператор continue досрочно завершает текущую итерацию цикла.
        # Python проигнорирует весь код ниже и сразу перейдет к следующему серверу в списке.
        continue

    # Если сервер прошел проверку (он online), добавляем его метрики в соответствующие списки.
    active_nodes.append(node_name)
    cpu_loads.append(cpu_load)
    ram_usages.append(ram_usage)

# Рассчитываем количество активных узлов с помощью функции len().
active_count = len(active_nodes)

# Вычисляем среднюю нагрузку на CPU:
# 1. sum(cpu_loads) находит сумму всех элементов в списке.
# 2. Делим сумму на количество серверов active_count.
# 3. round(..., 2) округляет результат до двух знаков после запятой.
# Тернарный оператор (if-else в одну строку) защищает программу от ZeroDivisionError (деления на ноль),
# если вдруг абсолютно все сервера окажутся офлайн.
avg_cpu = round(sum(cpu_loads) / active_count, 2) if active_count > 0 else 0.0

# Находим пиковое (максимальное) значение использования оперативной памяти с помощью встроенной функции max().
# Здесь также используется защита на случай отсутствия активных серверов.
peak_ram = max(ram_usages) if active_count > 0 else 0

# Формируем итоговый отчет в виде вложенного словаря.
# Такая структура данных часто используется для последующей отправки в формате JSON или YAML.
report = {
    'active_nodes_count': active_count,  # Метрика верхнего уровня
    'metrics': {  # Вложенный словарь со специфичными показателями
        'average_cpu': avg_cpu,
        'max_ram': peak_ram
    }
}

# Выводим в консоль список имен серверов, которые сейчас находятся в сети.
print(f"Активные узлы в сети: {active_nodes}")
print("Итоговый отчет телеметрии:")

# Импортируем модуль pprint (Pretty Print) для красивого отображения сложных структур данных.
import pprint

# Вызываем функцию pprint. Параметр sort_dicts=False запрещает сортировать ключи по алфавиту,
# сохраняя оригинальный порядок добавления элементов, который мы определили в словаре report.
pprint.pprint(report, sort_dicts=False)
