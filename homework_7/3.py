# Исходный словарь конфигурации. Содержит вложенный словарь "connection" с настройками базы данных.
config = {
    "connection": {
        "host": "production-db.internal",
        "port": 5432,
        "user": "postgres"
    }
}

# Извлекаем вложенный словарь по ключу "connection".
# Метод .get("connection", {}) безопасен: если ключа не окажется, программа не выдаст ошибку KeyError,
# а вернет пустой словарь {}. Переменная conn_dict становится ссылкой на внутренний словарь.
conn_dict = config.get("connection", {})

# Извлекаем конкретные параметры из полученного словаря conn_dict.
# Если ключи "host" или "port" отсутствуют, методы вернут значение None (по умолчанию).
host = conn_dict.get("host")
port = conn_dict.get("port")

# Пример "чейн-вызова" (цепочки методов .get) для работы с глубоко вложенными структурами:
# 1. config.get("ssl_settings", {}) ищет настройки SSL. Так как этого ключа нет, возвращается пустой словарь {}.
# 2. У этого пустого словаря вызывается второй .get("ssl_mode", "verify-full").
# 3. Ключа "ssl_mode" в пустом словаре нет, поэтому срабатывает резервное (дефолтное) значение — "verify-full".
ssl_mode = config.get("ssl_settings", {}).get("ssl_mode", "verify-full")

# Изменяем существующее значение в словаре conn_dict по ключу "user".
# Так как conn_dict ссылается на внутреннюю часть config, это изменение отразится и в исходном словаре config.
conn_dict["user"] = "admin"

# Добавляем совершенно новый ключ "max_connections" и присваиваем ему числовое значение.
conn_dict["max_connections"] = 100

# Выводим в консоль значение переменной ssl_mode, полученное на шаге с дефолтным значением.
print(f"SSL Mode: {ssl_mode}")
print("Параметры соединения:")

# Перебираем содержимое словаря conn_dict по парам "ключ-значение".
# Метод .items() превращает словарь в список кортежей (пар), что позволяет нам в цикле for
# распаковывать их сразу в две переменные: key (название параметра) и value (его значение).
for key, value in conn_dict.items():
    # Печатаем каждую пару в виде маркированного списка с помощью f-строки
    print(f"* {key}: {value}")
