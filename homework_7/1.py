# Исходная строка, содержащая сырые данные пользователя с лишними пробелами и разным регистром.
# Элементы разделены точкой с запятой (;).
stroka = " 10827 ; aLeXanDer_vLaDimiRov ; mInSk ; ACTIVE "

# Создаем пустой список, в который будем складывать очищенные от пробелов элементы.
cleaned_elements = []

# Запускаем цикл для обработки каждого фрагмента строки.
# Метод split(";") разрезает строку на части везде, где встречается символ ";".
for item in stroka.split(";"):
    # Метод strip() удаляет все скрытые и видимые пробелы в начале и в конце текущей строки 'item'.
    # Очищенную строку добавляем в наш список cleaned_elements с помощью append().
    cleaned_elements.append(item.strip())

# Распаковываем список из 4-х очищенных элементов в четыре отдельные переменные.
# Порядок строго соответствует порядку элементов в исходной строке.
uid, name, city, status = cleaned_elements

# Форматируем UID: используем f-строку, чтобы добавить статический префикс "UID-" перед самим номером.
uid = f"UID-{uid}"

# Корректируем имя:
# 1. replace("_", " ") заменяет нижнее подчеркивание на обычный пробел.
# 2. title() переводит первую букву каждого слова в верхний регистр, а остальные — в нижний (aLeXanDer_vLaDimiRov -> Alexander Vladimirov).
name = name.replace("_", " ").title()

# Переводим название города полностью в ВЕРХНИЙ регистр (mInSk -> MINSK).
city = city.upper()

# Переводим статус полностью в нижний регистр (ACTIVE -> active).
status = status.lower()

# Собираем переменные обратно в одну строку.
# Метод join() объединяет элементы списка в текст, вставляя между ними разделитель " | ".
normalized_record = " | ".join([uid, name, city, status])

# Выводим финальный результат в консоль с помощью f-строки.
print(f"Нормализованная запись: {normalized_record}")
